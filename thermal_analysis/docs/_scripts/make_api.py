"""Generate docs/api.md from the docstrings of the thermal_analysis package.

Usage, from anywhere:

    python thermal_analysis/docs/_scripts/make_api.py

The script reads the source with ast and imports nothing, so it works
without numba or PyRth. Run it again after you change a docstring, a
signature, or the STATUS and NOTES tables below.
"""

from __future__ import annotations

import ast
from pathlib import Path

from _tool import DOCS, PACKAGE_DIR

# Who calls each function, directly or through pipeline.analyse.
# Keep this table in step with gui/ and cli.py.
GUI, CLI = "window", "command line"
BOTH = (GUI, CLI)
STATUS = {
    **{name: BOTH for name in (
        "analyse", "identify_foster", "dZ_dln_t", "optimize_M_range_parallel",
        "optimize_tau_sequential_parallel", "refine_foster_least_squares",
        "reconstruct_foster", "my_deconv", "detect_min_max", "refine_peak", "safe_log_time",
        "filter_poles_min_resistance", "cauer_structure_function_max_test",
        "filter_cumulative_min_resistance", "differential_structure_function",
        "foster_to_cauer", "write_ltspice", "base_name", "cauer_cells")},
    **{name: (GUI,) for name in (
        "generate_foster_signal", "pad", "clean_array", "read_for_window", "parse_text",
        "results_table", "two_columns", "export_pdf")},
    "export_excel": BOTH,
    **{name: (CLI,) for name in (
        "cumulative_structure_function", "read_table", "write_cli_outputs", "plot_code",
        "parse_args", "main")},
}
NOTES = {
    "foster_network": "Broken: written as a method (takes `self`) and calls "
                      "`np.interp.InterpolatedUnivariateSpline`, which doesn't exist. "
                      "Don't call it.",
    "my_deconv_numba": "Not used. Unlike `my_deconv`, it doesn't clip the spectrum "
                       "or skip non-finite updates.",
    "reconstruct_foster_numba": "Not used.",
    "optimize_M_range": "Not used: sequential version of `optimize_M_range_parallel`, "
                        "without the coarse-then-fine search.",
    "optimize_tau_sequential": "Not used: same result as "
                               "`optimize_tau_sequential_parallel`.",
    "spectrum_to_foster": "Not used.",
    "spectrum_to_foster_max_detection_test": "Experimental, not used.",
    "spectrum_to_foster_max_detection_test_log2": "Experimental, not used.",
    "structure_function_from_spectrum": "Experimental, not used. Its third output "
                                        "is τ, not a derivative.",
    "foster_to_cauer": "The docstring lists the outputs as (Cs, Rs); the function "
                       "returns (Rs, Cs).",
    "refine_foster_least_squares": "`max_poles` only limits the poles the function "
                                   "adds. If the input already has more poles, the "
                                   "fit is skipped. Removes the poles below "
                                   "`config.MIN_POLE_RESISTANCE` when "
                                   "`config.FILTER_SMALL_POLES` is True.",
    "filter_poles_min_resistance": "Called by `refine_foster_least_squares` when "
                                   "`config.FILTER_SMALL_POLES` is True.",
    "differential_structure_function": "Unit of the output: J·W/K², that is W²·s/K².",
    "generate_foster_signal": "Takes capacitances `C`, not time constants, despite "
                              "the docstring; prints nothing.",
    "pad": "Also truncates: an array longer than N is cut to N elements.",
    "main": "Entry point of `python -m thermal_analysis -file ...`.",
}
MODULE_ORDER = ["pipeline", "data_io", "ltspice", "cli", "utils", "deconvolution", "foster",
                "optimization", "cauer", "structure_functions"]


def signature(node: ast.FunctionDef) -> str:
    return f"{node.name}({ast.unparse(node.args)})"


def module_files():
    name = PACKAGE_DIR.name
    return name, [(f"{name}.{m}", PACKAGE_DIR / f"{m}.py") for m in MODULE_ORDER]


def used_by(name):
    who = STATUS.get(name)
    return " and ".join(who) if who else "nothing"


def main():
    kind, files = module_files()
    out = [
        "# Code reference",
        "",
        "Every public function of the package, with its signature and its "
        "docstring as written in the code. This page is generated by "
        "`docs/_scripts/make_api.py`: don't edit it by hand. For how the "
        "functions fit together, see [How the identification works](method.md); "
        "for the settings they read, see "
        "[Settings and switches](reference.md#settings-and-switches). The window "
        "(`gui/`) is described in [Window, command line and files](reference.md).",
        "",
        "## Summary",
        "",
        "| Function | Module | Used by | Note |",
        "|---|---|---|---|",
    ]
    body = []
    for module, path in files:
        tree = ast.parse(Path(path).read_text(encoding="utf-8"))
        mod_doc = None
        for node in tree.body:
            if (isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant)
                    and isinstance(node.value.value, str)):
                mod_doc = node.value.value.strip()
                break
        body += ["", f"## {module}", ""]
        if mod_doc:
            body += [mod_doc, ""]
        for node in tree.body:
            if not isinstance(node, ast.FunctionDef) or node.name.startswith("_"):
                continue
            doc = ast.get_docstring(node)
            note = NOTES.get(node.name, "")
            out.append(f"| [`{node.name}`](#{node.name.lower()}) | `{module}` | "
                       f"{used_by(node.name)} | {note} |")
            body += [f"### {node.name}", "", "```python", signature(node), "```", ""]
            body += [f"Used by: {used_by(node.name)}.", ""]
            if note:
                body += [f"Note: {note}", ""]
            body += (["```text", doc, "```", ""] if doc else ["No docstring.", ""])
    text = "\n".join(out + body).rstrip() + "\n"
    (DOCS / "api.md").write_text(text, encoding="utf-8")
    print("written", DOCS / "api.md")


if __name__ == "__main__":
    main()
